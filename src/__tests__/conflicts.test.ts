import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { findFileConflicts, looseFiles } from '../backend/skyrim/fileConflicts';
import { moveMod, movePlugin } from '../backend/skyrim/mo2Profile';
import type { Instance, ModEntry } from '../backend/skyrim/modManager';
import { moveLine, moveRefusal, type PluginKind } from '../backend/skyrim/orderMoves';

const roots: string[] = [];
afterAll(() => {
    for (const root of roots) fs.rmSync(root, { recursive: true, force: true });
});

function write(file: string, text = '') {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
}

/** A Mod Organizer instance's folders as the readers take them: three mods, two of them sharing files. */
function makeInstance() {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'skyrim-conflicts-'));
    roots.push(root);
    const profileDir = path.join(root, 'profiles', 'Default');
    const instance: Instance = {
        instanceDir: root, gameDir: path.join(root, 'game'), edition: 'Steam', release: 'SkyrimSE' as Instance['release'],
        profile: 'Default', profileDir, modsDir: path.join(root, 'mods'), overwriteDir: path.join(root, 'overwrite'),
        downloadsDir: path.join(root, 'downloads')
    };
    write(path.join(profileDir, 'modlist.txt'), '# This file was automatically generated by Mod Organizer.\r\n+High\r\n+Middle\r\n-Off\r\n+Low\r\n');
    write(path.join(profileDir, 'plugins.txt'), '# This file was automatically generated by Mod Organizer.\r\n*Low.esp\r\n*Middle.esp\r\n*High.esp\r\n');
    write(path.join(profileDir, 'loadorder.txt'), '# This file was automatically generated by Mod Organizer.\r\nSkyrim.esm\r\nUpdate.esm\r\nLow.esp\r\nMiddle.esp\r\nHigh.esp\r\n');
    write(path.join(instance.modsDir, 'Low', 'textures', 'armor', 'Iron.dds'), 'low');
    write(path.join(instance.modsDir, 'Low', 'meta.ini'), '[General]');
    write(path.join(instance.modsDir, 'Low', 'Low.esp'));
    write(path.join(instance.modsDir, 'Low', 'Low.bsa'));
    write(path.join(instance.modsDir, 'High', 'Textures', 'Armor', 'iron.dds'), 'high');
    write(path.join(instance.modsDir, 'High', 'meta.ini'), '[General]');
    write(path.join(instance.modsDir, 'High', 'High.esp'));
    write(path.join(instance.modsDir, 'Middle', 'Middle.esp'));
    write(path.join(instance.modsDir, 'Middle', 'Middle - Textures.bsa'));
    write(path.join(instance.modsDir, 'Off', 'textures', 'armor', 'iron.dds'), 'off');
    fs.mkdirSync(instance.overwriteDir, { recursive: true });
    const mods: ModEntry[] = [
        { name: 'High', enabled: true, managed: true }, { name: 'Middle', enabled: true, managed: true },
        { name: 'Off', enabled: false, managed: true }, { name: 'Low', enabled: true, managed: true }
    ];
    return { instance, mods };
}

describe('moving a line', () => {
    it('puts it just before or after another, and says when it stood there already', () => {
        const lines = ['A', 'B', 'C', 'D'];
        expect(moveLine(lines, l => l === 'A', l => l === 'C', 'after')).toBe(true);
        expect(lines).toEqual(['B', 'C', 'A', 'D']);
        expect(moveLine(lines, l => l === 'D', l => l === 'B', 'before')).toBe(true);
        expect(lines).toEqual(['D', 'B', 'C', 'A']);
        expect(moveLine(lines, l => l === 'B', l => l === 'D', 'after')).toBe(false);
        expect(moveLine(lines, l => l === 'X', l => l === 'D', 'after')).toBe(false);
    });
});

describe('the rules a plugin move keeps', () => {
    const order = ['Skyrim.esm', 'Update.esm', 'Base.esm', 'Low.esp', 'Patch.esp', 'High.esp'];
    const kinds = new Map<string, PluginKind>([
        ['base.esm', { masters: ['Skyrim.esm'], master: true }],
        ['low.esp', { masters: ['Skyrim.esm'], master: false }],
        ['patch.esp', { masters: ['Skyrim.esm', 'Low.esp'], master: false }],
        ['high.esp', { masters: ['Skyrim.esm'], master: false }]
    ]);
    const primary = new Set(['skyrim.esm', 'update.esm']);
    const refusal = (plugin: string, where: 'before' | 'after', target: string) => moveRefusal(order, plugin, where, target, kinds, primary);

    it('allows a plain plugin among plain ones, in any letter case', () => {
        expect(refusal('low.esp', 'after', 'high.esp')).toMatch(/Patch\.esp names Low\.esp as a master/);
        expect(refusal('High.esp', 'before', 'Low.esp')).toBeUndefined();
    });

    it('keeps a plugin after its masters', () => {
        expect(refusal('Patch.esp', 'before', 'Low.esp')).toMatch(/Patch\.esp names Low\.esp as a master, and a plugin loads after its masters/);
    });

    it('refuses a move across the line between masters and plain plugins', () => {
        expect(refusal('Base.esm', 'after', 'High.esp')).toMatch(/Base\.esm is flagged master and High\.esp is not/);
    });

    it('leaves the game\'s own plugins in their order', () => {
        expect(refusal('Update.esm', 'after', 'High.esp')).toMatch(/one of the game's own plugins/);
        expect(refusal('High.esp', 'before', 'Skyrim.esm')).toMatch(/nothing loads before it/);
    });

    it('names a plugin no load order has', () => {
        expect(refusal('Gone.esp', 'after', 'High.esp')).toMatch(/Gone\.esp is in no load order/);
        expect(refusal('High.esp', 'after', 'High.esp')).toMatch(/name another/);
    });
});

describe('Mod Organizer\'s files, moved', () => {
    it('moves a plugin in plugins.txt and loadorder.txt, CRLF and the header kept', () => {
        const { instance } = makeInstance();
        expect(movePlugin(instance, 'Low.esp', 'after', 'High.esp')).toBe(true);
        expect(fs.readFileSync(path.join(instance.profileDir, 'plugins.txt'), 'latin1'))
            .toBe('# This file was automatically generated by Mod Organizer.\r\n*Middle.esp\r\n*High.esp\r\n*Low.esp\r\n');
        expect(fs.readFileSync(path.join(instance.profileDir, 'loadorder.txt'), 'utf8')).toMatch(/High\.esp\r\nLow\.esp\r\n$/);
        expect(movePlugin(instance, 'Low.esp', 'after', 'High.esp')).toBe(false);
    });

    it('moves a mod: after another in the mod order is above it in modlist.txt, the highest first', () => {
        const { instance } = makeInstance();
        expect(moveMod(instance, 'Low', 'after', 'High')).toBe(true);
        expect(fs.readFileSync(path.join(instance.profileDir, 'modlist.txt'), 'utf8'))
            .toBe('# This file was automatically generated by Mod Organizer.\r\n+Low\r\n+High\r\n+Middle\r\n-Off\r\n');
        expect(moveMod(instance, 'High', 'before', 'Middle')).toBe(true);
        expect(fs.readFileSync(path.join(instance.profileDir, 'modlist.txt'), 'utf8')).toMatch(/\+Low\r\n\+Middle\r\n\+High\r\n-Off\r\n$/);
    });
});

describe('file conflicts', () => {
    it('lists a mod\'s files under Data as the game compares them, meta.ini left out', () => {
        const { instance } = makeInstance();
        expect(looseFiles(path.join(instance.modsDir, 'Low')).sort()).toEqual(['low.bsa', 'low.esp', 'textures\\armor\\iron.dds']);
    });

    it('takes the mod order for loose files, a disabled mod none, and a loose file over any archive', async () => {
        const { instance, mods } = makeInstance();
        const asked: string[][] = [];
        const conflicts = await findFileConflicts(instance, mods, ['Skyrim.esm', 'Low.esp', 'Middle.esp', 'High.esp'], async ({ archives }) => {
            asked.push(archives.map(a => path.basename(a)));
            return { files: Object.fromEntries(archives.map(a => [a, ['textures\\armor\\iron.dds', 'meshes\\shared.nif']])) };
        }, { limit: 25 });
        // The archives in the load order of their plugins: Low's, then Middle's.
        expect(asked).toEqual([['Low.bsa', 'Middle - Textures.bsa']]);
        expect(conflicts.pairs).toEqual(expect.arrayContaining([
            { winner: 'High', loser: 'Low', how: 'mod order', files: 1, examples: ['textures\\armor\\iron.dds'] },
            { winner: 'High', loser: 'Low', how: 'loose over archive', files: 1, examples: ['textures\\armor\\iron.dds'] },
            { winner: 'High', loser: 'Middle', how: 'loose over archive', files: 1, examples: ['textures\\armor\\iron.dds'] },
            { winner: 'Middle', loser: 'Low', how: 'load order', files: 1, examples: ['meshes\\shared.nif'] }
        ]));
        expect(conflicts.pairs.some(pair => pair.loser === 'Off' || pair.winner === 'Off')).toBe(false);
        expect(conflicts.total).toBe(4);
    });

    it('narrows to one mod\'s, and reads no archive without the helper', async () => {
        const { instance, mods } = makeInstance();
        const conflicts = await findFileConflicts(instance, mods, ['Low.esp', 'Middle.esp', 'High.esp'], undefined, { mod: 'middle', limit: 25 });
        expect(conflicts).toEqual({ pairs: [], total: 0 });
        const low = await findFileConflicts(instance, mods, [], undefined, { mod: 'Low', limit: 25 });
        expect(low.pairs).toEqual([{ winner: 'High', loser: 'Low', how: 'mod order', files: 1, examples: ['textures\\armor\\iron.dds'] }]);
    });
});
