/**
 * Sorting the load order with LOOT (sortPlugins): libloot's answer turned into moves and LOOT's word on the setup, and the
 * order written into the profile's files only with `apply`. libloot itself is a fake here, as the helper is elsewhere: its
 * own tests are libloot's.
 */

const roots: string[] = [];
afterAll(() => { for (const root of roots) fs.rmSync(root, { recursive: true, force: true }); });
const temp = (prefix: string) => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
    roots.push(dir);
    return dir;
};

describe('orderChanges and reorderedLines', () => {
    it('names the fewest plugins to move, each just after the one it then follows, and they make the sorted order', () => {
        const current = ['Skyrim.esm', 'A.esp', 'B.esp', 'C.esp', 'D.esp'];
        const sorted = ['Skyrim.esm', 'C.esp', 'A.esp', 'B.esp', 'D.esp'];
        const moves = orderChanges(current, sorted);
        expect(moves).toEqual([{ plugin: 'C.esp', from: 4, to: 2, after: 'Skyrim.esm' }]);
        const applied = moves.reduce((order, move) => movedOrder(order, move.plugin, 'after', move.after!), current);
        expect(applied).toEqual(sorted);
        expect(orderChanges(current, current)).toEqual([]);
    });

    it('writes a whole order into a plugin list\'s own lines: each keeps its mark, comments and unnamed plugins their place', () => {
        const lines = ['# This file was automatically generated by Mod Organizer.', '*A.esp', 'Off.esp', '*B.esp', '*C.esp'];
        expect(reorderedLines(lines, ['Skyrim.esm', 'C.esp', 'A.esp', 'B.esp']))
            .toEqual(['# This file was automatically generated by Mod Organizer.', '*C.esp', 'Off.esp', '*A.esp', '*B.esp']);
        expect(reorderedLines(lines, ['A.esp', 'B.esp', 'C.esp'])).toBeUndefined();
    });
});

/** A libloot that sorts by the order `wanted` gives, and knows the metadata `meta` gives each plugin. */
function fakeLibloot(wanted: string[], meta: Record<string, object> = {}, crcs: Record<string, number> = {}, files: string[] = []) {
    const seen: { local?: string; dataPaths?: string[]; masterlist?: string; userlist?: string } = {};
    class Game implements Partial<LootGame> {
        private order: { name: string; active: boolean }[] = [];
        constructor(_type: number, _gamePath: string, local?: string) { seen.local = local; }
        setAdditionalDataPaths(paths: string[]) { seen.dataPaths = paths; }
        database() {
            return {
                loadMasterlistWithPrelude: (masterlist: string) => { seen.masterlist = masterlist; },
                loadUserlist: (userlist: string) => { seen.userlist = userlist; },
                generalMessages: () => [{ messageType: 0, content: [{ text: 'Your Skyrim is up-to-date.' }] }],
                pluginMetadata: (name: string) => meta[name] ? { group: null, messages: [], requirements: [], incompatibilities: [], dirtyInfo: [], ...meta[name] } : null,
                evaluate: (condition: string) => files.some(file => condition === `file(${JSON.stringify(file)})`)
            };
        }
        loadCurrentLoadOrderState() {
            this.order = fs.readFileSync(path.join(seen.local!, 'Plugins.txt'), 'latin1').split(/\r?\n/).filter(Boolean)
                .map(line => ({ name: line.replace(/^\*/, ''), active: line.startsWith('*') }));
        }
        loadOrder() { return this.order.map(plugin => plugin.name); }
        isPluginActive(name: string) { return this.order.find(plugin => plugin.name === name)?.active ?? false; }
        loadPlugins() { /* read by the fake's metadata */ }
        plugin(name: string) { return { name: () => name, crc: () => crcs[name] ?? null, masters: () => [], isMaster: () => false, isLightPlugin: () => false }; }
        sortPlugins(names: string[]) { return [...names].sort((a, b) => wanted.indexOf(a) - wanted.indexOf(b)); }
    }
    const module = { GameType: { SkyrimSE: 5 }, Game, liblootVersion: () => '0.29.7' } as unknown as LiblootModule;
    return { module, seen };
}

describe('lootSort', () => {
    it('hands libloot the profile\'s order in asterisk form and the mod folders, and says what LOOT says, warnings first', () => {
        const name = (text: string) => ({ asStr: () => text });
        const { module, seen } = fakeLibloot(['Skyrim.esm', 'Patch.esp', 'Big.esp', 'Old.esp'], {
            'Big.esp': {
                messages: [{ messageType: 1, content: [{ text: 'Big.esp is outdated.' }] }],
                dirtyInfo: [{ crc: 0xabc, itmCount: 3, deletedReferenceCount: 1, deletedNavmeshCount: 0, cleaningUtility: '[SSEEdit v4.1.5d](https://x)' },
                    { crc: 0x123, itmCount: 9, deletedReferenceCount: 9, deletedNavmeshCount: 0, cleaningUtility: 'SSEEdit' }],
                requirements: [{ name: name('SKSE/Plugins/BigHelper.dll'), displayName: 'Big Helper' }, { name: name('Present.esm'), displayName: null }]
            },
            'Patch.esp': { incompatibilities: [{ name: name('Old.esp'), displayName: null }, { name: name('Absent.esp'), displayName: null }] }
        }, { 'Big.esp': 0xabc }, ['Present.esm']);
        const workDir = temp('loot-work-');
        const { report, sorted } = lootSort({
            libloot: module, gameDir: 'G:/Skyrim', masterlist: 'M.yaml', prelude: 'P.yaml', workDir, dataPaths: ['G:/mo2/overwrite', 'G:/mo2/mods/Big'],
            order: [{ name: 'Skyrim.esm', active: true }, { name: 'Big.esp', active: true }, { name: 'Off.esp', active: false },
                { name: 'Patch.esp', active: true }, { name: 'Old.esp', active: true }]
        });
        expect(fs.readFileSync(path.join(workDir, 'Plugins.txt'), 'latin1')).toBe('*Skyrim.esm\r\n*Big.esp\r\nOff.esp\r\n*Patch.esp\r\n*Old.esp\r\n');
        expect(seen).toMatchObject({ dataPaths: ['G:/mo2/overwrite', 'G:/mo2/mods/Big'], masterlist: 'M.yaml' });
        expect(sorted).toEqual(['Skyrim.esm', 'Patch.esp', 'Big.esp', 'Old.esp']);
        expect(report).toMatchObject({
            plugins: 4, changed: true, moves: [{ plugin: 'Patch.esp', from: 3, to: 2, after: 'Skyrim.esm' }],
            messages: [{ level: 'warn', text: 'Big.esp is outdated.', plugin: 'Big.esp' }, { level: 'info', text: 'Your Skyrim is up-to-date.' }],
            // Only the version the plugin is, by its CRC.
            dirty: [{ plugin: 'Big.esp', itm: 3, deletedReferences: 1, deletedNavmeshes: 0, utility: 'SSEEdit v4.1.5d' }],
            missing: [{ plugin: 'Big.esp', needs: 'Big Helper' }],
            incompatible: [{ plugin: 'Patch.esp', with: 'Old.esp' }]
        });
    });
});

describe('sortPlugins', () => {
    /** A Mod Organizer instance with two mods' plugins out of LOOT's order. */
    function instance() {
        const root = temp('skyrim-loot-test-');
        const write = (file: string, content = '') => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); };
        const game = path.join(root, 'game');
        const dir = path.join(root, 'mo2');
        write(path.join(game, 'SkyrimSE.exe'));
        write(path.join(game, 'Data', 'Skyrim.esm'));
        write(path.join(dir, 'ModOrganizer.ini'), ['[General]', 'gameName=Skyrim Special Edition', `gamePath=@ByteArray(${game.replace(/\\/g, '\\\\')})`,
            'selected_profile=@ByteArray(Default)', 'game_edition=Steam', ''].join('\r\n'));
        const profile = path.join(dir, 'profiles', 'Default');
        write(path.join(profile, 'modlist.txt'), '+Late\r\n+Early\r\n');
        write(path.join(profile, 'plugins.txt'), '# This file was automatically generated by Mod Organizer.\r\n*Late.esp\r\n*Early.esp\r\n');
        write(path.join(profile, 'loadorder.txt'), 'Skyrim.esm\r\nLate.esp\r\nEarly.esp\r\n');
        for (const mod of ['Late', 'Early']) write(path.join(dir, 'mods', mod, `${mod}.esp`));
        fs.mkdirSync(path.join(dir, 'overwrite'), { recursive: true });
        const helper: HelperTransport = { running: false, async start() { }, stop() { }, async call() { throw new Error('no helper here'); } };
        const { module, seen } = fakeLibloot(['Skyrim.esm', 'Early.esp', 'Late.esp']);
        const engine = new SkyrimEngine(new Mo2Manager(dir, currentPlatform()), helper, path.join(root, 'projects'), {
            platform: currentPlatform(), lootCacheDir: path.join(root, 'cache'),
            loot: { library: async () => module, masterlist: async () => ({ masterlist: 'M.yaml', prelude: 'P.yaml' }) }
        });
        return { profile, dir, seen, backend: new SkyrimInstanceBackend({ engine }) };
    }

    it('previews LOOT\'s order and writes nothing; with apply writes it into plugins.txt and loadorder.txt', async () => {
        const fixture = instance();
        const handler = createHandlers(fixture.backend as unknown as AppBackend, CORE_PRODUCT).find(h => h.getTools().some(t => t.name === 'sortPlugins'))!;
        const call = async (args: object) => JSON.parse((await handler.handle('sortPlugins', args)).content[0].text);
        const files = () => ['plugins.txt', 'loadorder.txt'].map(file => fs.readFileSync(path.join(fixture.profile, file), 'utf8'));
        const before = files();

        const preview = await call({});
        expect(preview).toMatchObject({ changed: true, applied: false, moves: [{ plugin: 'Early.esp', to: 2, after: 'Skyrim.esm' }] });
        expect(preview.nextStep).toMatch(/^A preview: LOOT would move 1 plugin\(s\), as `moves` says; nothing was written\. sortPlugins with "apply": true writes/);
        expect(files()).toEqual(before);
        // The mods' folders, the highest priority first, after the overwrite: the folders the game sees as Data.
        expect(fixture.seen.dataPaths).toEqual([path.join(fixture.dir, 'overwrite'), path.join(fixture.dir, 'mods', 'Late'), path.join(fixture.dir, 'mods', 'Early')]);

        const applied = await call({ apply: true });
        expect(applied).toMatchObject({ applied: true });
        expect(applied.nextStep).toMatch(/^LOOT's order is written: 1 plugin\(s\) moved\./);
        expect(files()).toEqual(['# This file was automatically generated by Mod Organizer.\r\n*Early.esp\r\n*Late.esp\r\n', 'Skyrim.esm\r\nEarly.esp\r\nLate.esp\r\n']);
        expect((await call({ apply: true })).nextStep).toMatch(/^LOOT's order is the profile's already: nothing to move\./);
    });
});
